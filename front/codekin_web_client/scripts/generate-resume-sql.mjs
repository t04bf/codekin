import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

// Frontend manifest is the single source for built-in template configuration.
const root = fileURLToPath(new URL('../', import.meta.url))
const project = path.resolve(root, '../..')
const templates = JSON.parse(await readFile(path.join(root, 'src/features/resume/data/templates.json'), 'utf8'))
const content = JSON.parse(await readFile(path.join(root, 'src/features/resume/data/blank-content.json'), 'utf8'))
const draft = await readFile(path.join(project, 'dosc/resume-schema-draft.sql'), 'utf8')
// Only adopt table DDL; editorial comments from the earlier draft are not a migration.
const ddl = [...draft.matchAll(/CREATE TABLE [\s\S]+?;(?=\n)/g)].map(match => match[0].replace('CREATE TABLE ', 'CREATE TABLE IF NOT EXISTS ')).join('\n\n')
if (ddl.match(/CREATE TABLE/g)?.length !== 3) throw new Error('Expected exactly three resume tables')
if (new Set(templates.map(t => `${t.templateKey}@${t.templateVersion}`)).size !== templates.length) throw new Error('Duplicate template version')
// Encode UTF-8 as hex so SQL_MODE and apostrophes/backslashes cannot change JSON values.
const str = value => `CONVERT(X'${Buffer.from(value, 'utf8').toString('hex')}' USING utf8mb4)`
let sql = '-- Generated by front/codekin_web_client/scripts/generate-resume-sql.mjs.\n'
sql += '-- 简历表与9套内置模板。仅创建缺失表/模板版本，不覆盖既有版本。\n'
sql += '-- 内置模板ID固定保留于910000000000000001—910000000000000009；普通实体仍使用ASSIGN_ID。\n'
sql += '-- 不创建导出任务表。执行前选择数据库；应用时间使用UTC。\n\n' + ddl + '\n\n'
sql += 'START TRANSACTION;\n'
for (const t of templates) {
  if (!/^\d+$/.test(t.id)) throw new Error('Invalid template id')
  sql += `\n-- ${t.templateKey}@${t.templateVersion} ${t.name}\n`
  sql += 'INSERT INTO resume_template\n    (id, template_key, template_version, name, description, cover_path, schema_version, default_content, default_layout, status, sort_order)\n'
  sql += `SELECT ${t.id}, ${str(t.templateKey)}, ${t.templateVersion}, ${str(t.name)}, ${str(t.description)}, NULL, ${t.schemaVersion},\n    ${str(JSON.stringify(content))},\n    ${str(JSON.stringify(t.defaultLayout))}, ${str(t.status)}, ${t.sortOrder}\n`
  sql += `WHERE NOT EXISTS (SELECT 1 FROM resume_template WHERE template_key = ${str(t.templateKey)} AND template_version = ${t.templateVersion});\n`
}
sql += '\nCOMMIT;\n'
const begin = '-- BEGIN GENERATED RESUME SCHEMA AND TEMPLATES'
const end = '-- END GENERATED RESUME SCHEMA AND TEMPLATES'
const deployPath = path.join(project, 'deploy/deploy.sql')
const deploy = await readFile(deployPath, 'utf8')
const existing = deploy.indexOf(begin)
if (existing >= 0 && !deploy.includes(end)) throw new Error('Unclosed generated block')
const next = existing < 0 ? `${deploy.trimEnd()}\n\n${begin}\n${sql}${end}\n` : deploy.slice(0, existing) + `${begin}\n${sql}${end}` + deploy.slice(deploy.indexOf(end) + end.length)
for (const [file, expected] of [[path.join(project, 'deploy/sql/20261005_resume_templates.sql'), sql], [deployPath, next]]) {
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== expected) throw new Error(`Generated SQL out of sync: ${file}`)
  } else await writeFile(file, expected)
}
console.log(`Verified ${templates.length} template versions; SQL ${process.argv.includes('--check') ? 'matches' : 'generated'}.`)
